import { readFileSync, writeFileSync } from "node:fs";

// A plugin/reader over the deck+map: where the corpus's attention MOVED over time. Needs dates
// (frontmatter created_at/date); silently skips a corpus without them.
type TD = { dates?: (number | undefined)[]; saved?: number[]; cluster: number[]; scores: Record<string, number[]>; axes: { key: string; name: string; low: string; high: string }[]; clusters: { c: number; n: number; label: string }[] };

const median = (a: number[]) => { const s = a.slice().sort((x, y) => x - y); return s[s.length >> 1]; };
const ym = (ms: number) => new Date(ms).toISOString().slice(0, 7);

export function trajectory(D: TD): string | null {
  const dates = (D.dates ?? D.saved ?? []).map((x) => x || 0);
  const valid = dates.map((d, i) => ({ d, i })).filter((x) => x.d > 0);
  if (valid.length < 20) return null;
  const med = median(valid.map((x) => x.d));
  const early = new Set(valid.filter((x) => x.d <= med).map((x) => x.i)), late = new Set(valid.filter((x) => x.d > med).map((x) => x.i));
  const nE = early.size || 1, nL = late.size || 1;
  const R = ["# State of the corpus — auto-generated portrait", "", `*${valid.length} dated cards · split at ${ym(med)}*`, "", "## Where attention is moving (share of cards, first half → second half)"];
  const rows = D.clusters.map((c) => {
    const idxs = D.cluster.map((cc, i) => (cc === c.c ? i : -1)).filter((i) => i >= 0);
    const e = idxs.filter((i) => early.has(i)).length, l = idxs.filter((i) => late.has(i)).length;
    return { d: l / nL - e / nE, label: c.label, e, l };
  }).sort((a, b) => b.d - a.d);
  for (const r of rows) R.push(`- ${r.d > 0.008 ? "📈 rising" : r.d < -0.008 ? "📉 cooling" : "· steady"} — **${r.label}**: ${r.e} → ${r.l}  (${(r.d * 100).toFixed(1)} pts)`);
  R.push("", "## Center-of-mass drift on the axes");
  for (const a of D.axes) {
    const s = D.scores[a.key]; if (!s) continue;
    const mean = (set: Set<number>) => { let t = 0, n = 0; set.forEach((i) => { t += s[i] || 0; n++; }); return n ? t / n : 0; };
    const e = mean(early), l = mean(late);
    if (Math.abs(l - e) >= 1.5) R.push(`- **${a.name}**: ${e.toFixed(0)} → ${l.toFixed(0)} → *${l > e ? a.high : a.low}*`);
  }
  R.push("", "---", "*Regenerated by eidoscope.*");
  return R.join("\n");
}

if (import.meta.main) {
  const D = JSON.parse(readFileSync((process.env.EIDOSCOPE_FIXTURE ?? ".") + "/mde-data.json", "utf8"));
  const md = trajectory({ saved: D.saved, cluster: D.cluster, scores: D.scores, axes: D.axes, clusters: D.clusters });
  if (md) { writeFileSync("STATE.md", md); console.log(md.split("\n").slice(0, 15).join("\n"), "\n\n✅ trajectory works — STATE.md written"); }
  else console.log("⚠ not enough dated docs");
}
